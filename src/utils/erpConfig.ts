export const SQL_WAREHOUSE_SCHEMA = `-- ============================================================================
-- MULTI-COMPANY RFB & RBI CONSTRUCTION SYSTEM — OLTP & DATA WAREHOUSE DDL
-- HQ: P-1 A Brgy. Doongan, Butuan City, Agusan Del Norte | Currency: PHP
-- ============================================================================

CREATE TABLE companies (
  company_id      VARCHAR(20) PRIMARY KEY,
  company_code    VARCHAR(10) UNIQUE NOT NULL, -- 'RFB' or 'RBI'
  company_name    VARCHAR(150) NOT NULL,
  legal_name      VARCHAR(200) NOT NULL,
  theme_primary   VARCHAR(10) NOT NULL,        -- '#123E82' (RFB) | '#113E2B' (RBI)
  is_active       BOOLEAN DEFAULT TRUE
);

CREATE TABLE users (
  user_id             VARCHAR(30) PRIMARY KEY,
  username            VARCHAR(80) UNIQUE NOT NULL,
  password_hash       TEXT NOT NULL,
  employee_code       VARCHAR(30) NOT NULL,
  full_name           VARCHAR(150) NOT NULL,
  department          VARCHAR(100) NOT NULL,
  position            VARCHAR(120) NOT NULL,
  role_label          VARCHAR(120) NOT NULL,
  is_admin            BOOLEAN DEFAULT FALSE,
  account_status      VARCHAR(20) DEFAULT 'Active', -- 'Active' | 'Inactive' | 'Resigned' | 'Suspended'
  employment_status   VARCHAR(20) DEFAULT 'Regular',
  must_change_pw      BOOLEAN DEFAULT TRUE,
  date_created        DATE NOT NULL,
  last_login          TIMESTAMP,
  created_by          VARCHAR(80) NOT NULL,
  updated_by          VARCHAR(80) NOT NULL
);

CREATE TABLE user_company_access (
  access_id       BIGSERIAL PRIMARY KEY,
  user_id         VARCHAR(30) NOT NULL REFERENCES users(user_id),
  company_id      VARCHAR(20) NOT NULL REFERENCES companies(company_id),
  role_label      VARCHAR(100) NOT NULL,
  allowed_modules TEXT[] NOT NULL,
  UNIQUE (user_id, company_id)
);

CREATE TABLE user_company_permissions (
  perm_id         BIGSERIAL PRIMARY KEY,
  user_id         VARCHAR(30) NOT NULL REFERENCES users(user_id),
  company_id      VARCHAR(20) NOT NULL REFERENCES companies(company_id),
  permission_key  VARCHAR(60) NOT NULL,        -- e.g. 'approve_transactions'
  UNIQUE (user_id, company_id, permission_key)
);

CREATE TABLE projects (
  project_id              VARCHAR(20) PRIMARY KEY,
  company_id              VARCHAR(20) NOT NULL REFERENCES companies(company_id),
  project_code            VARCHAR(30) NOT NULL,
  project_name            VARCHAR(150) NOT NULL,
  project_type            VARCHAR(30) CHECK (project_type IN ('Road','Bridge','Building','Administrative')),
  location                VARCHAR(150) NOT NULL,
  client_owner            VARCHAR(150) NOT NULL,
  description             TEXT,
  project_manager         VARCHAR(120) NOT NULL,
  start_date              DATE NOT NULL,
  target_completion_date  DATE NOT NULL,
  actual_completion_date  DATE,
  approved_budget         NUMERIC(14,2) NOT NULL,
  status                  VARCHAR(30) DEFAULT 'Ongoing' CHECK (status IN ('Planning','Not Yet Started','Ongoing','On Hold','Completed','Cancelled')),
  progress_pct            INT DEFAULT 0 CHECK (progress_pct BETWEEN 0 AND 100),
  remarks                 TEXT,
  UNIQUE (company_id, project_code)
);

CREATE TABLE audit_logs (
  audit_id        BIGSERIAL PRIMARY KEY,
  user_id         VARCHAR(30) NOT NULL,
  company_id      VARCHAR(20) NOT NULL REFERENCES companies(company_id),
  module_name     VARCHAR(50) NOT NULL,
  action_name     VARCHAR(100) NOT NULL,
  target_id       VARCHAR(60),
  details         TEXT,
  created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_date (
  date_key        INT PRIMARY KEY,
  full_date       DATE NOT NULL,
  month_num       INT NOT NULL,
  quarter_num     INT NOT NULL,
  year_num        INT NOT NULL
);

CREATE TABLE dim_project (
  project_key     SERIAL PRIMARY KEY,
  company_id      VARCHAR(20) NOT NULL REFERENCES companies(company_id),
  project_code    VARCHAR(30) NOT NULL,
  project_name    VARCHAR(150) NOT NULL,
  project_type    VARCHAR(30) NOT NULL,
  location        VARCHAR(150) NOT NULL,
  budget_amount   NUMERIC(14,2) NOT NULL
);

CREATE TABLE fact_procurement (
  fact_id         BIGSERIAL PRIMARY KEY,
  company_id      VARCHAR(20) NOT NULL REFERENCES companies(company_id),
  date_key        INT REFERENCES dim_date(date_key),
  project_key     INT REFERENCES dim_project(project_key),
  supplier_key    INT NOT NULL,
  material_code   VARCHAR(30) NOT NULL,
  qty_ordered     NUMERIC(12,2) NOT NULL,
  unit_cost       NUMERIC(12,2) NOT NULL,
  total_spend     NUMERIC(14,2) NOT NULL,
  canvass_savings NUMERIC(14,2) DEFAULT 0
);
`;
